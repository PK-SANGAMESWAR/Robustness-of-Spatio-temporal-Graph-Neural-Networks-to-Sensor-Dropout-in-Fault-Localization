#!/usr/bin/env python3
"""
Generate pmu_phase_metadata.yaml by compiling the IEEE 123-bus feeder and
reading Bus.Nodes() for each of the 25 μPMU buses.

This is the AUTHORITATIVE source of μPMU phase types.  It replaces the
defective approach of inferring phase count from the maximum phase count
of incident feeder lines (which incorrectly classifies single/two-phase
devices attached to three-phase segments).

Usage:
    python scripts/generate_pmu_metadata.py [--output config/pmu_phase_metadata.yaml]

Run once after environment setup and commit the resulting YAML to the repo.
The output is consumed by `measured_only.py:classify_pmu_nodes()`.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Allow running as a script from the project root
sys.path.insert(0, str(Path(__file__).parent.parent))

import yaml  # type: ignore

from fault_localization.config.constants import PMU_BUSES, GREEN_FEEDER_OPEN_SWITCH_BUSES, GREEN_FEEDER_CLOSE_SWITCH_BUSES
from fault_localization.simulation.feeder import compile_feeder, ensure_feeder_files

import opendssdirect as dss


def get_pmu_phase_metadata() -> dict[int, int]:
    """Compile the feeder and read Bus.Nodes() for each μPMU bus.

    Returns
    -------
    dict[int, int]
        bus_id → number of phases (1, 2, or 3).
    """
    master_path = ensure_feeder_files()
    compile_feeder(master_path)

    metadata: dict[int, int] = {}
    for bus_id in PMU_BUSES:
        dss.Circuit.SetActiveBus(str(bus_id))
        nodes = dss.Bus.Nodes()
        # Count phase nodes (1=A, 2=B, 3=C); exclude neutral (0)
        phase_nodes = [n for n in nodes if 1 <= n <= 3]
        n_phases = len(phase_nodes)
        if n_phases == 0:
            n_phases = 3  # conservative fallback if bus not found
        metadata[bus_id] = n_phases

    return metadata


def get_switch_names() -> dict[str, str | None]:
    """Discover the OpenDSS Line names for the green feeder switches.

    Handles the OpenDSS convention where normally-open buses are named with
    an ``_open`` suffix (e.g., bus 94 appears as ``94_open``).
    """
    open_a, open_b = GREEN_FEEDER_OPEN_SWITCH_BUSES
    close_a, close_b = GREEN_FEEDER_CLOSE_SWITCH_BUSES

    switch_names: dict[str, str | None] = {}

    for label, bus_a, bus_b in [
        ("open_switch_60_160", open_a, open_b),
        ("close_switch_54_94", close_a, close_b),
    ]:
        # Match plain bus IDs and the OpenDSS _open suffix variant
        targets_a = {str(bus_a).lower(), f"{bus_a}_open"}
        targets_b = {str(bus_b).lower(), f"{bus_b}_open"}
        flag = dss.Lines.First()
        found = None
        while flag > 0:
            b1 = dss.Lines.Bus1().split(".")[0].lower()
            b2 = dss.Lines.Bus2().split(".")[0].lower()
            if (b1 in targets_a and b2 in targets_b) or (
                b1 in targets_b and b2 in targets_a
            ):
                found = dss.Lines.Name()
                break
            flag = dss.Lines.Next()
        switch_names[label] = found
        if found is None:
            print(
                f"WARNING: Could not find Line element for buses {bus_a}–{bus_b}. "
                f"Green feeder switching may not work.",
                file=sys.stderr,
            )
        else:
            print(f"  Found {label}: Line.{found}")

    return switch_names


def main(output_path: Path) -> None:
    print("Compiling IEEE 123-bus feeder …")
    metadata = get_pmu_phase_metadata()

    print("\nμPMU phase classification (from Bus.Nodes()):")
    three_phase = [b for b, p in metadata.items() if p == 3]
    partial = [b for b, p in metadata.items() if p < 3]
    print(f"  Three-phase buses ({len(three_phase)}): {sorted(three_phase)}")
    print(f"  Partial-phase buses ({len(partial)}): {sorted(partial)}")

    print("\nDiscovering green feeder switch names …")
    switch_names = get_switch_names()

    doc = {
        "# μPMU phase metadata — AUTO-GENERATED by scripts/generate_pmu_metadata.py": None,
        "# DO NOT hand-edit.  Re-run the script after any feeder model update.": None,
        "# Source: Bus.Nodes() from OpenDSS after compiling IEEE123Master.dss.": None,
        "pmu_phase_metadata": {int(k): int(v) for k, v in metadata.items()},
        "green_feeder_switch_names": {k: v for k, v in switch_names.items()},
    }

    output_path.parent.mkdir(parents=True, exist_ok=True)
    # Write cleanly without the comment-key hack
    with open(output_path, "w") as f:
        f.write(
            "# μPMU phase metadata — AUTO-GENERATED by scripts/generate_pmu_metadata.py\n"
            "# DO NOT hand-edit.  Re-run the script after any feeder model update.\n"
            "# Source: Bus.Nodes() from OpenDSS after compiling IEEE123Master.dss.\n\n"
        )
        yaml.dump(
            {
                "pmu_phase_metadata": {int(k): int(v) for k, v in metadata.items()},
                "green_feeder_switch_names": {k: v for k, v in switch_names.items()},
            },
            f,
            default_flow_style=False,
            sort_keys=True,
        )

    print(f"\nSaved → {output_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    # Default: always write to <project_root>/config/pmu_phase_metadata.yaml
    # regardless of where this script is invoked from.
    _default_output = Path(__file__).parent.parent / "config" / "pmu_phase_metadata.yaml"
    parser.add_argument(
        "--output",
        type=Path,
        default=_default_output,
        help=f"Output YAML path (default: {_default_output})",
    )
    args = parser.parse_args()
    main(args.output)
