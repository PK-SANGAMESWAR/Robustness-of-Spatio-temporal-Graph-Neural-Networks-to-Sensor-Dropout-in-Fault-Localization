"""Build dataset figures + the Dataset Information table for the paper, computed
ENTIRELY from the real dataset files (no hand-entered numbers).

Produces:
  paper/tables/dataset_info.tex        — LaTeX table (counts from labels/splits)
  paper/figures/measured_only_graph.png — the 25-node measured-only graph (edge_index)
  paper/figures/fault_signature.png     — real voltage sag at 0.1/1/10 Ohm (raw_sim)

Every number is derived from dataset_<tag>/ files or fault_localization.config.constants;
nothing is copied from the base paper. Run offline (CPU) — does not touch training.

Usage:
    uv run python scripts/build_dataset_assets.py --data-root dataset_fullscale_50
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import json
import numpy as np
import pandas as pd

from fault_localization.config import constants as C

# Figure palette (matches the project's other figures)
INK = "#0b0b0b"; INK_SECONDARY = "#52514e"; INK_MUTED = "#898781"
GRID = "#e1e0d9"; SURFACE = "#fcfcfb"
PHASE_COLOR = {1: "#eda100", 2: "#1baf7a", 3: "#2a78d6"}  # 1-/2-/3-phase muPMU
RES_COLOR = {0.1: "#184f95", 1.0: "#2a78d6", 10.0: "#6da7ec"}


# ---------------------------------------------------------------------------
# 1. Dataset Information table — computed from real labels + splits
# ---------------------------------------------------------------------------
def build_table(data_root: Path, out_dir: Path, runs_per_scenario: int) -> dict:
    labels = pd.read_csv(data_root / "processed" / "labels.csv")   # window_id, fault_bus, label
    label_of = dict(zip(labels["window_id"], labels["label"]))

    rows = {}
    for split in ("train", "val", "test"):
        ids = (data_root / "splits" / f"{split}.txt").read_text().split()
        labs = np.array([label_of[i] for i in ids])
        n_total = len(labs)
        n_nofault = int((labs == 0).sum())
        n_fault = int((labs != 0).sum())
        n_events = n_total // C.WINDOWS_PER_EVENT
        rows[split] = dict(total=n_total, fault=n_fault, nofault=n_nofault, events=n_events)

    grand = {k: sum(rows[s][k] for s in rows) for k in ("total", "fault", "nofault", "events")}

    # LaTeX table
    def fmt(n): return f"{n:,}"
    tex = rf"""% AUTO-GENERATED by scripts/build_dataset_assets.py — do not hand-edit counts.
\begin{{table}}[!ht]
\centering
\caption{{Dataset configuration and window-level distribution for the frozen
\texttt{{{data_root.name}}} corpus ({runs_per_scenario} runs/scenario). All counts are
computed directly from the generated dataset.}}
\label{{tab:dataset}}
\footnotesize
\begin{{tabular}}{{@{{}}ll@{{}}}}
\toprule
\multicolumn{{2}}{{@{{}}l}}{{\textit{{Simulation configuration}}}} \\
\midrule
Test feeder            & IEEE 123-bus, {C.FEEDER_NOMINAL_KV:g}\,kV, {C.FEEDER_FREQUENCY_HZ:g}\,Hz \\
Simulator              & OpenDSS (OpenDSSDirect.py), Daily {C.SAMPLING_RESOLUTION_MS}\,ms step \\
Fault positions        & {C.NUM_FAULT_BUSES} buses \\
$\mu$PMU locations     & {C.NUM_PMU_NODES} buses (single-/two-/three-phase) \\
Fault types            & {C.NUM_FAULT_TYPES} (3 LG, 3 LL, 3 LLG, 2 three-phase) \\
Fault resistances      & {C.NUM_RESISTANCES} ({', '.join(f'{r:g}' for r in C.FAULT_RESISTANCES)}\,$\Omega$) \\
Load multiplier        & $\mathcal{{U}}({C.LOAD_MULTIPLIER_LOW:g}, {C.LOAD_MULTIPLIER_HIGH:g})$ per run \\
Scenarios (factorial)  & ${C.NUM_FAULT_BUSES}\times{C.NUM_FAULT_TYPES}\times{C.NUM_RESISTANCES} = {C.NUM_SCENARIOS}$ \\
Runs per scenario      & {runs_per_scenario} \\
Record / window        & {C.TOTAL_RECORD_MS}\,ms record ({C.PRE_FAULT_MS}\,ms pre-fault), {C.WINDOW_LENGTH}-step ({C.WINDOW_LENGTH}\,ms) windows \\
Windows per event      & {C.WINDOWS_PER_EVENT} \\
Node features $F$      & {C.NUM_FEATURES} ($[V_1,V_2,V_3]$ + availability mask $[m_1,m_2,m_3]$) \\
Classes                & {C.NUM_CLASSES} ({C.NUM_FAULT_BUSES} locations + no-fault) \\
\addlinespace
\multicolumn{{2}}{{@{{}}l}}{{\textit{{Window-level distribution (event-level 70/15/15 split)}}}} \\
\midrule
Split & Fault / No-fault / Total (events) \\
\midrule
Train      & {fmt(rows['train']['fault'])} / {fmt(rows['train']['nofault'])} / {fmt(rows['train']['total'])} ({fmt(rows['train']['events'])}) \\
Validation & {fmt(rows['val']['fault'])} / {fmt(rows['val']['nofault'])} / {fmt(rows['val']['total'])} ({fmt(rows['val']['events'])}) \\
Test       & {fmt(rows['test']['fault'])} / {fmt(rows['test']['nofault'])} / {fmt(rows['test']['total'])} ({fmt(rows['test']['events'])}) \\
\midrule
Total      & {fmt(grand['fault'])} / {fmt(grand['nofault'])} / {fmt(grand['total'])} ({fmt(grand['events'])}) \\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "dataset_info.tex").write_text(tex)
    return {"rows": rows, "grand": grand}


# ---------------------------------------------------------------------------
# 2. Measured-only graph figure — from real edge_index + pmu phase metadata
# ---------------------------------------------------------------------------
def build_graph_figure(data_root: Path, out_dir: Path) -> dict:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    import networkx as nx
    import yaml

    edge_index = np.load(data_root / "processed" / "edge_index.npy")
    node_mapping = json.loads((data_root / "processed" / "node_mapping.json").read_text())
    idx_to_bus = {v: int(k) for k, v in node_mapping.items()}

    meta_path = Path("fault_localization/data/ieee123/config/pmu_phase_metadata.yaml")
    phase_meta = yaml.safe_load(meta_path.read_text())["pmu_phase_metadata"]

    G = nx.Graph()
    G.add_nodes_from(range(len(node_mapping)))
    for s, d in zip(edge_index[0], edge_index[1]):
        if s != d:
            G.add_edge(int(s), int(d))

    phase_of = {i: int(phase_meta[idx_to_bus[i]]) for i in G.nodes}
    fault_set = set(C.FAULT_BUSES)
    # nodes that are ALSO fault locations (measured fault buses)
    node_is_fault = {i: (idx_to_bus[i] in fault_set) for i in G.nodes}

    pos = nx.kamada_kawai_layout(G) if nx.is_connected(G) else nx.spring_layout(G, seed=42)

    plt.rcParams.update({"figure.facecolor": SURFACE, "axes.facecolor": SURFACE,
                         "font.family": "sans-serif", "text.color": INK, "font.size": 11})
    # Canvas is kept short and wide: the figure is placed at ~0.85\linewidth in the
    # single-column Procedia layout, so a low aspect ratio buys page space while the
    # larger font sizes below keep the node labels legible after down-scaling.
    fig, ax = plt.subplots(figsize=(6.5, 4.2))
    nx.draw_networkx_edges(G, pos, ax=ax, edge_color=INK_MUTED, width=1.4)
    for ph in (1, 2, 3):
        nodes = [n for n in G.nodes if phase_of[n] == ph]
        nx.draw_networkx_nodes(G, pos, nodelist=nodes, ax=ax, node_size=520,
                               node_color=PHASE_COLOR[ph], edgecolors=INK, linewidths=1.0)
    # ring-highlight nodes that are also fault locations
    fnodes = [n for n in G.nodes if node_is_fault[n]]
    nx.draw_networkx_nodes(G, pos, nodelist=fnodes, ax=ax, node_size=760,
                           node_color="none", edgecolors="#c0392b", linewidths=2.2)
    nx.draw_networkx_labels(G, pos, labels={i: idx_to_bus[i] for i in G.nodes},
                            ax=ax, font_size=10, font_color=INK)
    handles = [Line2D([0], [0], marker="o", linestyle="", markersize=10,
                      markerfacecolor=PHASE_COLOR[p], markeredgecolor=INK,
                      label=f"{p}-phase $\\mu$PMU") for p in (1, 2, 3)]
    handles.append(Line2D([0], [0], marker="o", linestyle="", markersize=12,
                          markerfacecolor="none", markeredgecolor="#c0392b",
                          label="also a fault location"))
    ax.legend(handles=handles, frameon=False, loc="upper left", fontsize=10)
    # No in-figure title: the LaTeX caption carries it (and saves vertical space).
    ax.axis("off")
    fig.tight_layout()
    out_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_dir / "measured_only_graph.png", dpi=400)
    plt.close(fig)
    n_measured_faults = sum(node_is_fault.values())
    return {"n_nodes": G.number_of_nodes(), "n_edges": G.number_of_edges(),
            "connected": nx.is_connected(G), "n_fault_also_pmu": n_measured_faults}


# ---------------------------------------------------------------------------
# 3. Fault-signature figure — REAL voltage sag at 0.1/1/10 Ohm from raw_sim
# ---------------------------------------------------------------------------
def build_signature_figure(data_root: Path, out_dir: Path,
                           bus: int = 101, ftype: str = "ABCG", run: int = 0) -> dict:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    res_tag = {0.1: "0p1", 1.0: "1p0", 10.0: "10p0"}
    raw = data_root / "raw_sim"
    plt.rcParams.update({"figure.facecolor": SURFACE, "axes.facecolor": SURFACE,
                         "font.family": "sans-serif", "text.color": INK,
                         "axes.labelcolor": INK, "xtick.color": INK_SECONDARY,
                         "ytick.color": INK_SECONDARY, "font.size": 11})
    fig, ax = plt.subplots(figsize=(6.5, 2.8))
    ax.spines["top"].set_visible(False); ax.spines["right"].set_visible(False)
    ax.spines["left"].set_color(INK_MUTED); ax.spines["bottom"].set_color(INK_MUTED)
    ax.grid(color=GRID, linewidth=1, zorder=0); ax.set_axisbelow(True); ax.tick_params(length=0)

    sag_report = {}
    t = np.arange(C.NUM_TIMESTEPS)  # ms
    for r in (0.1, 1.0, 10.0):
        f = raw / f"{bus}_{ftype}_{res_tag[r]}_{run:04d}.npz"
        if not f.exists():
            continue
        data = np.load(f)["data"]           # [25, 60, 6]
        volt = data[:, :, 0:3]              # phase voltage magnitudes
        prefault = volt[:, :C.FAULT_START_STEP, :].mean(axis=1, keepdims=True)  # per node/phase
        prefault = np.where(prefault == 0, np.nan, prefault)
        vpu = volt / prefault               # normalize each channel to its own pre-fault mean
        # deepest-sagging (node, phase) channel during the fault window
        fault_win = vpu[:, C.FAULT_START_STEP:, :]
        fault_min = float(np.nanmin(fault_win))
        node, _, phase = np.unravel_index(np.nanargmin(fault_win), fault_win.shape)
        trace = vpu[node, :, phase]
        ax.plot(t, trace, color=RES_COLOR[r], linewidth=2.2,
                label=f"{r:g} $\\Omega$ (sag {1 - fault_min:.2f} p.u.)", zorder=3)
        sag_report[r] = float(1 - fault_min)

    ax.axvline(C.FAULT_START_STEP, color=INK_MUTED, linestyle="--", linewidth=1.4, zorder=2)
    ax.text(C.FAULT_START_STEP - 0.8, 0.55, "fault inception", rotation=90,
            color=INK_MUTED, fontsize=9, va="center", ha="right")
    ax.set_xlabel("Time (ms)")
    ax.set_ylabel("Phase voltage (p.u.)")
    # No in-figure title: the LaTeX caption carries it (and saves vertical space).
    ax.legend(frameon=False, title="Fault resistance", loc="lower left", fontsize=9)
    fig.tight_layout()
    out_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_dir / "fault_signature.png", dpi=400)
    plt.close(fig)
    return {"bus": bus, "ftype": ftype, "sag_pu": sag_report}


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--data-root", default="dataset_fullscale_50")
    p.add_argument("--runs-per-scenario", type=int, default=50)
    args = p.parse_args()

    data_root = Path(args.data_root)
    fig_dir = Path("paper/figures")
    tab_dir = Path("paper/tables")

    tinfo = build_table(data_root, tab_dir, args.runs_per_scenario)
    ginfo = build_graph_figure(data_root, fig_dir)
    sinfo = build_signature_figure(data_root, fig_dir)

    print("=== VERIFICATION (all from real data) ===")
    print("Table splits:", {k: v["total"] for k, v in tinfo["rows"].items()},
          "grand total windows:", tinfo["grand"]["total"])
    print("  no-fault fraction:",
          round(tinfo["grand"]["nofault"] / tinfo["grand"]["total"], 4))
    print("Graph:", ginfo)
    print("Fault signature sag (p.u.):", sinfo["sag_pu"])
    print(f"\nWrote: {tab_dir}/dataset_info.tex, {fig_dir}/measured_only_graph.png, "
          f"{fig_dir}/fault_signature.png")


if __name__ == "__main__":
    main()
