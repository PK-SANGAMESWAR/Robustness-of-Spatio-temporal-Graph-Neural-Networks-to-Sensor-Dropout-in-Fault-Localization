"""Additive measurement noise for the μPMU robustness study.

The corpus is generated by OpenDSS and the voltages are read straight out of
the solver, so every baseline number in this project is measured on noise-free
inputs.  Field μPMUs are not noise-free: IEEE C37.118 admits a total vector
error of up to 1 % of nominal, and instrument transformers, quantization, and
the phasor estimator all contribute.  This module perturbs the voltage channels
at *inference* time so that the sensor-dropout results can be re-measured on
inputs that are degraded as well as incomplete.

Two details matter for correctness:

**Noise is specified in per-unit, applied in normalized space.**
``WindowGraphDataset`` z-scores voltage channels 0-2 with the training-split
statistics, so a batch reaching the model is already normalized.  A physical
standard deviation ``sigma_pu`` therefore enters as ``sigma_pu / std_c`` on
channel ``c``, with ``std_c`` read from ``processed/norm_stats.json``.  Passing
the physical value keeps the sweep interpretable (0.01 p.u. = 1 % of nominal)
without denormalizing and renormalizing the batch.

**Noise is gated by the availability mask.**
A channel whose mask bit is 0 carries no instrument — either a phase that unit
never measured (11 of the 25 μPMUs are not three-phase) or a sensor dropped by
the study's masking policy.  Adding noise there would manufacture a reading
where no sensor exists, and in the dropout case would partially undo the very
masking under test.  So noise lands only where ``m_{i,p}(s) = 1``.  Because a
dropped node has all six channels zeroed, this composes correctly with dropout
in either order.
"""

from __future__ import annotations

import numpy as np
import torch

# IEEE C37.118 caps total vector error at 1 % of nominal; the sweep brackets
# that with a laboratory-grade and a mid-range level.
DEFAULT_SIGMA_PU: list[float] = [0.0, 0.001, 0.005, 0.01]


def apply_measurement_noise_batch(
    x: torch.Tensor,
    sigma_pu: float,
    norm_std: np.ndarray | torch.Tensor,
    seed: int,
) -> torch.Tensor:
    """Add zero-mean Gaussian noise to the available voltage channels.

    Parameters
    ----------
    x:
        Batch tensor ``[B, N, S, 6]`` — z-scored voltages in channels 0-2 and
        binary availability mask in channels 3-5.
    sigma_pu:
        Noise standard deviation in **per-unit voltage** (0.01 = 1 % of
        nominal).  A non-positive value returns ``x`` unchanged.
    norm_std:
        Per-channel voltage standard deviation used to normalize the corpus
        (``norm_stats.json``'s ``std``), length 3.
    seed:
        Seed for the noise draw.  Callers must vary it with the batch index,
        for the same reason ``evaluate_dropout_curve`` varies its mask seed:
        a constant seed would repeat one ``[B, N, S, 3]`` noise field for every
        batch and collapse the number of realizations to ``batch_size``.

    Returns
    -------
    torch.Tensor
        ``x`` with noise added to voltage channels wherever the corresponding
        mask channel is active.  The mask channels themselves are never
        perturbed — they are categorical instrumentation flags, not signals.
    """
    if sigma_pu <= 0:
        return x

    std = torch.as_tensor(np.asarray(norm_std, dtype=np.float32),
                          device=x.device, dtype=x.dtype)
    if std.numel() != 3:
        raise ValueError(f"norm_std must have 3 entries, got {std.numel()}")

    # Physical p.u. sigma -> per-channel sigma in the model's normalized space.
    sigma = sigma_pu / std  # [3]

    generator = torch.Generator(device=x.device)
    generator.manual_seed(int(seed))

    volts = x[..., :3]
    avail = x[..., 3:] > 0.5  # instrumented and not dropped

    noise = torch.randn(volts.shape, generator=generator,
                        device=x.device, dtype=x.dtype) * sigma

    x_noisy = x.clone()
    x_noisy[..., :3] = volts + noise * avail
    return x_noisy
