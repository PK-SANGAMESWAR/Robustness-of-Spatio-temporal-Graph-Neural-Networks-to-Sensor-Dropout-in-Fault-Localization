"""Generate the feeder documents of the corpus (O7, 2026-10-31: "generated feeder docs") from the frozen repo sources.

Layout and document IDs follow session B's corpus v2 feeder documents (quarantined, `_quarantine_session2/`), so its golden
spans stay valid; session A added the nearest-μPMU distances on the operated feeder and the dropout protocol (author, 2026-10-31).
Sources (read only): fault_localization/config/constants.py, dataset_fullscale_50/processed/{node_mapping.json,edge_index.npy},
dataset_fullscale_50/splits/*.txt, config/pmu_phase_metadata.yaml and the OpenDSS IEEE 123 model. No value is typed by hand.
Output: rag-for-dropout/corpus/feeder_v1/*.md and MANIFEST.json (sha256 per file). Never overwrites.

    PYTHONPATH=src:. .venv/bin/python -m gridsense.ingest.feeder_docs [--out rag-for-dropout/corpus/feeder_v1]
"""
from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

import networkx as nx
import numpy as np
import yaml

from fault_localization.config import constants as C
from gridsense.config import ROOT, TRACK

DATA = ROOT / "dataset_fullscale_50"
PROCESSED = DATA / "processed"
GENERATOR_VERSION = "feeder_docs_v2"
KFT_TO_KM = 0.3048
OPENDSS_UNITS_KFT = 2  # OpenDSS LineUnits enum: 0 none, 1 mi, 2 kft, 3 km, 4 m, 5 ft
SOURCE_REF = "generated by gridsense.ingest.feeder_docs from constants.py, node_mapping.json, edge_index.npy, splits, pmu_phase_metadata.yaml, IEEE123Master.dss"


def _sources() -> dict[str, Path]:
    return {"constants": ROOT / "fault_localization/config/constants.py", "node_mapping": PROCESSED / "node_mapping.json",
            "edge_index": PROCESSED / "edge_index.npy", "phase_metadata": ROOT / "config/pmu_phase_metadata.yaml",
            "feeder_model": ROOT / "fault_localization/data/ieee123/IEEE123Master.dss",
            **{f"split_{s}": DATA / "splits" / f"{s}.txt" for s in ("train", "val", "test")}}


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def measured_graph() -> tuple[dict[int, int], dict[int, list[int]], dict[int, int], list[tuple[int, int]]]:
    """(bus -> node index, bus -> neighbour buses, bus -> instrumented phases, sorted edges) of the model's graph."""
    node_of = {int(b): i for b, i in json.loads((PROCESSED / "node_mapping.json").read_text()).items()}
    bus_of = {i: b for b, i in node_of.items()}
    nbrs: dict[int, set[int]] = {b: set() for b in node_of}
    for s, d in np.load(PROCESSED / "edge_index.npy").T:
        nbrs[bus_of[int(s)]].add(bus_of[int(d)])
    phases = {int(b): int(v) for b, v in yaml.safe_load(_sources()["phase_metadata"].read_text())["pmu_phase_metadata"].items()}
    edges = sorted({tuple(sorted((a, b))) for a, v in nbrs.items() for b in v})
    return node_of, {b: sorted(v) for b, v in nbrs.items()}, phases, edges


def feeder_distances() -> nx.Graph:
    """Electrical IEEE 123 feeder with edge attribute `km` (reports/findings/paper1_open_switch.md).

    `build_full_topology_graph` (frozen) stores kft as `length_km` and turns the open-point buses 300_OPEN and 94_OPEN into
    buses 300 and 94. Here: convert kft to km, give closed switches 0 km, remove every switch to an `_open` bus, require a tree.
    """
    import opendssdirect as dss
    from fault_localization.graph.measured_only import build_full_topology_graph
    from fault_localization.simulation.feeder import compile_feeder

    compile_feeder()
    open_sw, flag = set(), dss.Lines.First()
    while flag > 0:
        name, unit = dss.Lines.Name(), int(dss.Lines.Units())
        if dss.Lines.IsSwitch():
            if "_open" in (dss.Lines.Bus1() + dss.Lines.Bus2()).lower():
                open_sw.add(name)
        elif unit != OPENDSS_UNITS_KFT:
            raise RuntimeError(f"line {name}: length unit {unit}; expected kft ({OPENDSS_UNITS_KFT})")
        flag = dss.Lines.Next()
    G = build_full_topology_graph()
    G.remove_edges_from([(u, v) for u, v, e in G.edges(data=True) if e["name"] in open_sw])
    for _, _, e in G.edges(data=True):
        e["km"] = 0.0 if e["name"].startswith("sw") else e["length_km"] * KFT_TO_KM
    if not nx.is_tree(G):
        raise RuntimeError("feeder graph without the open switches is not a tree")
    G.graph["open_switches"] = sorted(open_sw)
    return G


def _front(doc_id: str, title: str) -> list[str]:
    return ["---", f"document_id: {doc_id}", f"title: {title}", "document_type: feeder_documentation", "status: generated",
            "approval_status: curated_for_research", f"source_ref: {SOURCE_REF}", "---", "", f"# {title}", ""]


def _split_counts() -> dict[str, tuple[int, int]]:
    out = {}
    for s in ("train", "val", "test"):
        ids = [l.strip() for l in (DATA / "splits" / f"{s}.txt").read_text().splitlines() if l.strip()]
        out[s] = (len({i.rsplit("_w", 1)[0] for i in ids}), len(ids))
    return out


def overview_doc() -> str:
    measured = [f for f in C.FAULT_BUSES if f in C.PMU_BUSES]
    sc = _split_counts()
    first = ", ".join(f"class {i + 1} = bus {b}" for i, b in enumerate(C.FAULT_BUSES[:5]))
    runs_per = sc["train"][0] + sc["val"][0] + sc["test"][0]
    L = _front("feeder_overview", "Feeder, sensors, classes and data windows")
    L += ["## System",
          f"The study feeder is the IEEE 123-bus distribution test feeder at {C.FEEDER_NOMINAL_KV:.2f} kV line-to-line and {C.FEEDER_FREQUENCY_HZ:.0f} Hz. It is simulated in OpenDSS.",
          f"The measurement set has {C.NUM_PMU_NODES} μPMU buses (bus 300 is a load/auxiliary bus). The graph used by the model is a {C.NUM_PMU_NODES}-node tree with {C.NUM_PMU_NODES - 1} edges between μPMU buses.",
          f"There are {C.NUM_FAULT_BUSES} candidate fault buses; {len(measured)} of them are μPMU buses ({', '.join(map(str, measured))}) and {C.NUM_FAULT_BUSES - len(measured)} are not measured directly.",
          "", "## Classes",
          f"The classifier has {C.NUM_CLASSES} classes. Class 0 means no fault. Class c from 1 to {C.NUM_FAULT_BUSES} is the fault bus listed at position c of the sorted fault-bus list: {first}, and so on (full table in the fault-bus document).",
          "", "## Scenarios and runs",
          f"A scenario is one fault bus, one fault type and one fault resistance: {C.NUM_FAULT_BUSES} × {C.NUM_FAULT_TYPES} × {C.NUM_RESISTANCES} = {C.NUM_SCENARIOS} scenarios. Each run of a scenario uses a different load multiplier (range {C.LOAD_MULTIPLIER_LOW} to {C.LOAD_MULTIPLIER_HIGH}). The frozen corpus has {runs_per // C.NUM_SCENARIOS} runs per scenario. A run is named <bus>_<type>_<resistance>_<run>, for example 57_ABCG_10p0_0014 (resistance 10.0 Ω written 10p0).",
          "", "## Data window",
          f"Each run records {C.TOTAL_RECORD_MS} ms at {C.SAMPLING_RESOLUTION_MS} ms resolution: {C.PRE_FAULT_MS} ms before the fault and {C.FAULT_DURATION_MS} ms of fault. A window has {C.WINDOW_LENGTH} time steps (stride {C.WINDOW_STRIDE}) and holds, for each of the {C.NUM_PMU_NODES} nodes, {C.NUM_FEATURES} channels: 3 RMS phase voltages and 3 availability-mask channels. Shape: [{C.NUM_PMU_NODES} nodes, {C.WINDOW_LENGTH} steps, {C.NUM_FEATURES} channels]. Each run keeps {C.WINDOWS_PER_EVENT} windows, named w0000 to w{C.WINDOWS_PER_EVENT - 1:04d}.",
          "", "## Window labels",
          "Windows w0000 to w0019 end before the fault and have label 0. Windows from w0020 carry the fault-bus class. Window w0020 ends exactly at fault onset and holds no post-fault sample. A window w ≥ 21 holds w − 20 post-fault samples; w0025 holds 5.",
          "", "## Splits",
          "The split divides runs, not scenarios, so every scenario appears in train, validation and test. "
          f"Runs: train {sc['train'][0]:,}, validation {sc['val'][0]:,}, test {sc['test'][0]:,}. Windows: train {sc['train'][1]:,}, validation {sc['val'][1]:,}, test {sc['test'][1]:,}.",
          "", "## Sensor dropout protocol",
          f"Dropout removes k of the {C.NUM_PMU_NODES} μPMUs at random, with k in 0, 1, 2, 5 and 10 (0, 4, 8, 20 and 40 percent). A dropped μPMU has its three voltage channels and its three mask channels set to 0; its graph edges stay (policy zero_messages)."]
    return "\n".join(L) + "\n"


def taxonomy_doc() -> str:
    L = _front("feeder_fault_taxonomy", "Fault types and fault resistances")
    L += ["## Fault types", f"There are {C.NUM_FAULT_TYPES} fault types:", "",
          f"- line-to-ground (LG): {', '.join(C.LG_TYPES)}", f"- line-to-line (LL): {', '.join(C.LL_TYPES)}",
          f"- double line-to-ground (LLG): {', '.join(C.LLG_TYPES)}", f"- three-phase: {', '.join(C.THREE_PHASE_TYPES)}", "",
          "The letters are the faulted phases; a trailing G means the fault includes ground (ABG, ABCG). ABC is a three-phase fault without ground.",
          "", "## Fault resistance",
          f"Three fault resistances are simulated: {', '.join(f'{r:.1f}' for r in C.FAULT_RESISTANCES)} Ω. The 10 Ω faults draw the least current and are the hardest to localize."]
    return "\n".join(L) + "\n"


def fault_bus_doc(G: nx.Graph, node_of: dict[int, int], phases: dict[int, int]) -> str:
    L = _front("feeder_fault_buses", "Fault buses and class indices")
    L += ["Class 0 is no fault. Each row maps a class index to a candidate fault bus.", "",
          "| class | fault bus | μPMU at this bus | graph node index | phases at the μPMU |", "|---|---|---|---|---|"]
    for f in C.FAULT_BUSES:
        m = f in C.PMU_BUSES
        L.append(f"| {C.FAULT_BUS_TO_LABEL[f]} | {f} | {'yes' if m else 'no'} | {node_of[f] if m else '-'} | {phases[f] if m else '-'} |")
    unm = [f for f in C.FAULT_BUSES if f not in C.PMU_BUSES]
    L += ["", f"Unmeasured fault buses ({len(unm)}): {', '.join(map(str, unm))}.", "",
          "## Nearest μPMUs on the operated feeder",
          f"Distances are the shortest path along the lines of the OpenDSS model with the normally open switches ({', '.join(G.graph['open_switches'])}) open; "
          "line lengths in kft converted to km (1 kft = 0.3048 km); a closed switch counts as 0 km. Hops count line segments and closed switches. "
          "The model graph in the μPMU document was built by the paper code, which treats these two switches as closed, so 3 of its 24 edges differ from the operated feeder.", "",
          "| fault bus | nearest μPMU (km, hops) | 2nd nearest (km, hops) | 3rd nearest (km, hops) |", "|---|---|---|---|"]
    for f in C.FAULT_BUSES:
        d = nx.single_source_dijkstra_path_length(G, f, weight="km")
        hops = nx.single_source_shortest_path_length(G, f)
        near = sorted(((d[p], hops[p], p) for p in C.PMU_BUSES), key=lambda t: (t[0], t[2]))[:3]
        L.append(f"| {f} | " + " | ".join(f"bus {p} ({km:.3f} km, {h})" for km, h, p in near) + " |")
    return "\n".join(L) + "\n"


def pmu_doc(node_of, nbrs, phases, edges) -> str:
    n3 = sum(phases[b] == 3 for b in C.PMU_BUSES)
    n2 = sum(phases[b] == 2 for b in C.PMU_BUSES)
    n1 = sum(phases[b] == 1 for b in C.PMU_BUSES)
    L = _front("feeder_pmu_nodes", "μPMU nodes, phases and graph neighbours")
    L += [f"The {C.NUM_PMU_NODES} μPMU nodes form a tree with {len(edges)} edges. {n3} nodes measure three phases, {n2} measure two phases and {n1} measure one phase. "
          "The mask channels of a working node are static and encode these phases; a dropped node has all six channels set to 0.", "",
          "| node index | μPMU bus | phases | candidate fault bus (class) | neighbouring μPMU buses |", "|---|---|---|---|---|"]
    for b in sorted(C.PMU_BUSES, key=lambda x: node_of[x]):
        cls = C.FAULT_BUS_TO_LABEL.get(b, "-")
        L.append(f"| {node_of[b]} | {b} | {phases[b]} | {cls} | {', '.join(map(str, nbrs[b]))} |")
    L += ["", "## Edges", ", ".join(f"{a}–{b}" for a, b in edges) + "."]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=TRACK / "corpus" / "feeder_v1")
    a = ap.parse_args()
    if a.out.exists():
        raise SystemExit(f"{a.out} exists; the generator never overwrites (make a new version)")
    node_of, nbrs, phases, edges = measured_graph()
    docs = {"feeder_overview.md": overview_doc(), "feeder_fault_taxonomy.md": taxonomy_doc(),
            "feeder_fault_buses.md": fault_bus_doc(feeder_distances(), node_of, phases),
            "feeder_pmu_nodes.md": pmu_doc(node_of, nbrs, phases, edges)}
    a.out.mkdir(parents=True)
    entries = []
    for name, text in docs.items():
        (a.out / name).write_text(text, encoding="utf-8")
        entries.append({"document_id": Path(name).stem, "file": name, "document_type": "feeder_documentation",
                        "approval_status": "curated_for_research", "sha256": _sha(a.out / name)})
    manifest = {"corpus_part": a.out.name, "generator": GENERATOR_VERSION, "created_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                "sources": {k: {"path": str(p.relative_to(ROOT)), "sha256": _sha(p)} for k, p in _sources().items()},
                "note": "Generated. Never edit; regenerate into a new version folder.", "documents": entries}
    (a.out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"out": str(a.out), "files": [e["file"] for e in entries]}))


if __name__ == "__main__":
    main()
