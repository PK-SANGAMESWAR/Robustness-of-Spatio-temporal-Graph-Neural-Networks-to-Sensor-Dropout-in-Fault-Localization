"""Re-derive the sweep decisions and the headline numbers WITHOUT the two draft golden queries (R-0055 test, R-0056 dev), from the stored per-query results (author O34, 2026-11-02).
No retrieval run, no API call, no new use of the test split: the per-query metrics in the snapshots do not depend on other queries; only tau (dev) is refitted.

    PYTHONPATH=src:. .venv/bin/python -m gridsense.eval.reviewed_only_check
"""
from __future__ import annotations

import json

import numpy as np

from gridsense.config import ROOT, load_config
from gridsense.eval import retrieval_metrics as RM
from gridsense.eval.precision_check import latest
from gridsense.eval.sweep import CHUNKERS, EMBEDDERS, MODES, OVERLAPS, SIZES, SWEEPS, select

DRAFT = {"R-0055", "R-0056"}
AXIS_CANDS = {"chunker": CHUNKERS, "chunk_size": [f"size_{s}" for s in SIZES], "overlap": [f"overlap_{o:.2f}" for o in OVERLAPS], "embedder": EMBEDDERS,
              "retrieval_mode": MODES, "reranker": ["rerank_off", "rerank_on"], "candidates": ["cand_20", "cand_50"]}


def dev_items(label: str) -> list[dict]:
    snap = latest(label)
    return [x for x in map(json.loads, (ROOT / snap["items_path"]).read_text().splitlines()) if x["split"] == "dev" and x["answerable"] and "error" not in x and x["query_id"] not in DRAFT]


def winners_without_drafts() -> list[dict]:
    rec = json.loads((SWEEPS / "WINNERS.json").read_text())["axes"]
    out = []
    for axis, cands in AXIS_CANDS.items():
        names = [c for c in cands if not c.startswith("openai")] if axis == "embedder" else cands
        per_q, cost, splits = {}, {}, {}
        for c in names:
            items = dev_items(f"sweep_{axis}_{c}")
            per_q[c] = np.array([(x["mrr@10"] + x["recall@5"] + x["ndcg@5"]) / 3 for x in items])
            cost[c] = float(np.mean([x["ctx_tokens@5"] for x in items]))
            m = latest(f"sweep_{axis}_{c}")["metrics"]
            splits[c] = m["reachability.contexts"] - m["reachability.reachable"]
        ck = axis in ("chunker", "chunk_size", "overlap")
        sel = select(axis, per_q, cost=cost if ck else None, splits=splits)
        out.append({"axis": axis, "recorded": rec[axis]["winner"], "without_drafts": sel["winner"], "same": rec[axis]["winner"] == sel["winner"], "n_queries": len(next(iter(per_q.values())))})
    return out


def headline() -> dict:
    cfg = load_config()
    dev = dev_items("sweep_top_k_readout")
    tests = [x for x in map(json.loads, (ROOT / latest("frozen_final_test")["items_path"]).read_text().splitlines()) if x["split"] == "test" and "error" not in x and x["query_id"] not in DRAFT]
    devall = [x for x in map(json.loads, (ROOT / latest("sweep_top_k_readout")["items_path"]).read_text().splitlines()) if x["split"] == "dev" and "error" not in x and x["query_id"] not in DRAFT]
    tau = RM.choose_sufficiency_threshold([x["dense_top1"] for x in devall], [x["answerable"] for x in devall])
    ans = [x for x in tests if x["answerable"]]
    res = {"n_test_answerable": len(ans), "n_test_unanswerable": len(tests) - len(ans), "tau_dev": tau}
    for k in ("recall@1", "recall@3", "recall@5", "mrr@10", "ndcg@5", "precision@3", "precision@5"):
        res[k] = RM.aggregate(ans, k, cfg["repeats"]["bootstrap_resamples"])
    res["sufficiency_test"] = RM.sufficiency_metrics([x["dense_top1"] for x in tests], [x["answerable"] for x in tests], tau["tau"])
    return res


if __name__ == "__main__":
    w, h = winners_without_drafts(), headline()
    L = ["# Reviewed-only check (without the two draft queries)", "", "Written for: the author. Generated by `gridsense.eval.reviewed_only_check` from the stored per-query results; no retrieval run, no API call, no new use of the test split. "
         "R-0056 (dev) and R-0055 (test) are drafts since the O34 decision; the sweeps and the frozen test run had included them.", "",
         "## 1. Do the sweep winners change without R-0056 (24 dev queries)? (paid embedder excluded from the embedder axis)", "", "| axis | recorded winner | winner without the draft | same |", "|---|---|---|---|"]
    L += [f"| {x['axis']} | {x['recorded']} | {x['without_drafts']} | {'yes' if x['same'] else '**NO**'} |" for x in w]
    f = lambda m: f"{m['mean']:.2f} ({m['ci_low']:.2f}–{m['ci_high']:.2f})"
    s = h["sufficiency_test"]
    L += ["", f"## 2. Frozen configuration `final` on test, reviewed queries only ({h['n_test_answerable']} answerable, {h['n_test_unanswerable']} unanswerable; tau refitted on dev without R-0056 = {h['tau_dev']['tau']:.3f})", "",
          "| Recall@1 | Recall@3 | Recall@5 | MRR@10 | nDCG@5 | P@3 | P@5 | unanswerable flagged | answerable flagged |", "|---|---|---|---|---|---|---|---|---|",
          "| " + " | ".join(f(h[k]) for k in ("recall@1", "recall@3", "recall@5", "mrr@10", "ndcg@5", "precision@3", "precision@5")) + f" | {s['unanswerable_flagged_insufficient']:.2f} | {s['answerable_flagged_insufficient']:.2f} |", "",
          "These numbers replace the test numbers of `FROZEN_TEST.md` and `SUMMARY.md` (those included the draft R-0055). They come from the same single run on the test split."]
    (SWEEPS / "REVIEWED_ONLY.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (SWEEPS / "REVIEWED_ONLY.json").write_text(json.dumps({"winners": w, "headline": h}, indent=1, default=float))
    print("\n".join(L))
