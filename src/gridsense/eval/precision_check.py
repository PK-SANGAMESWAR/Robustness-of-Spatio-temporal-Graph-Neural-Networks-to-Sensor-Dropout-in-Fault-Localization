"""Precision of the frozen retrieval configuration: precision@k, normalized precision@k, R-precision, on dev and test (author, 2026-11-02). Reviewed queries only.

    PYTHONPATH=src:. .venv/bin/python -m gridsense.eval.precision_check --config final

Computed from the STORED retrieval lists (snapshots) and the stored chunk texts: no new retrieval run, no API call, no new use of the test split.
Definitions (per answerable query):
  relevant passage   a retrieved chunk whose text contains at least one golden span of the query (same document)
  M                  the number of relevant chunks in the whole index (with chunk overlap, one golden span can lie in two chunks, so M can exceed the number of golden spans)
  precision@k        relevant in the top k / k
  maximum            min(k, M) / k
  normalized P@k     precision@k / maximum = relevant in the top k / min(k, M)
  R-precision        relevant in the top M / M
"""
from __future__ import annotations

import argparse
import json

import numpy as np

from gridsense.config import ROOT, TRACK, load_config
from gridsense.eval import golden as G
from gridsense.eval import retrieval_metrics as RM
from gridsense.eval.layer1 import INDEX_DIR
from gridsense.eval.sweep import SWEEPS

KS = (1, 3, 5)
LABELS = {"final": {"dev": "sweep_top_k_readout", "test": "frozen_final_test"}, "final_v2": {"dev": "sweep_table_rows_table_rows_on", "test": "frozen_final_v2_test"}}


def latest(label: str) -> dict:
    snaps = sorted((TRACK / "eval" / "snapshots").glob(f"*_{label}.json"))
    if not snaps:
        raise SystemExit(f"no snapshot {label}")
    return json.loads(snaps[-1].read_text())


def load_run(label: str) -> tuple[list[dict], dict[str, dict]]:
    snap = latest(label)
    items = [json.loads(l) for l in (ROOT / snap["items_path"]).read_text().splitlines()]
    folder = INDEX_DIR / snap["index_fingerprint"][:16]
    chunks = {c["chunk_id"]: c for c in map(json.loads, (folder / "chunks.jsonl").read_text(encoding="utf-8").splitlines())}
    return items, chunks


def per_query(item: dict, row: dict, chunks: dict[str, dict]) -> dict:
    def rel(c: dict) -> bool:
        return any(G.matches(c["document_id"], c["text"], ctx) for ctx in row["golden_contexts"])
    m = sum(rel(c) for c in chunks.values() if c["document_id"] in {x["document_id"] for x in row["golden_contexts"]})
    flags = [rel(chunks[p["chunk_id"]]) for p in item["retrieved"]]
    out = {"M": m}
    for k in KS:
        top = sum(flags[:k])
        out[f"p@{k}"], out[f"p_max@{k}"] = top / k, min(k, m) / k
        out[f"np@{k}"] = top / min(k, m) if m else float("nan")
    out["r_precision"] = sum(flags[:m]) / m if m else float("nan")
    return out


def summarize(rows_ans: list[dict]) -> dict:
    res = {"n": len(rows_ans), "relevant_chunks_M": {str(k): int(sum(r["M"] == k for r in rows_ans)) for k in sorted({r["M"] for r in rows_ans})}}
    for key in [f"{p}@{k}" for k in KS for p in ("p", "p_max", "np")] + ["r_precision"]:
        v = [r[key] for r in rows_ans]
        lo, hi = RM.bootstrap_ci(v, 2000)
        res[key] = {"mean": float(np.mean(v)), "ci_low": lo, "ci_high": hi}
    return res


def run(config: str) -> dict:
    cfg = load_config()
    rows = {r["query_id"]: r for r in G.load(ROOT / cfg["golden_sets"]["retrieval"]["path"], statuses=("reviewed",))}
    out = {"config": config, "reviewed_queries_only": True}
    for split, label in LABELS[config].items():
        items, chunks = load_run(label)
        pq = [per_query(it, rows[it["query_id"]], chunks) for it in items if it["split"] == split and it["answerable"] and it["query_id"] in rows and "error" not in it]
        out[split] = summarize(pq)
        out[split]["snapshot"] = latest(label)["label"]
    return out


def write(res: dict, name: str = "PRECISION.md"):
    L = [f"# Precision of the frozen configuration `{res['config']}` (reviewed queries only)", "",
         "Written for: the author. Generated by `gridsense.eval.precision_check` from the stored retrieval lists and chunk texts (no new retrieval run, no API call, no new use of the test split). "
         "Draft queries (R-0055, R-0056) are excluded. 95 % intervals: bootstrap over queries.", "",
         "A passage is relevant if it contains a golden span of the query. M = the number of relevant chunks in the index (chunk overlap can put one span into two chunks). "
         "Normalized P@k = precision@k divided by its maximum min(k, M)/k for that query. R-precision = precision at rank M.", "",
         "| split | queries | P@1 | P@3 | P@5 | max P@3 | max P@5 | normalized P@1 | normalized P@3 | normalized P@5 | R-precision |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    f = lambda m: f"{m['mean']:.3f} ({m['ci_low']:.2f}–{m['ci_high']:.2f})"
    for split in ("dev", "test"):
        r = res[split]
        L.append(f"| {split} | {r['n']} | " + " | ".join([f(r["p@1"]), f(r["p@3"]), f(r["p@5"]), f"{r['p_max@3']['mean']:.3f}", f"{r['p_max@5']['mean']:.3f}", f(r["np@1"]), f(r["np@3"]), f(r["np@5"]), f(r["r_precision"])]) + " |")
    L += ["", "Relevant chunks per query (M → number of queries): " + "; ".join(f"{split}: " + ", ".join(f"{k} → {v}" for k, v in res[split]["relevant_chunks_M"].items()) for split in ("dev", "test")) + ".", "",
          "Reading: with M = 1 or 2 relevant chunks, plain P@3 can be at most 0.33 or 0.67 and P@5 at most 0.2 or 0.4. Normalized P@k removes that cap: 1.0 means that every relevant chunk that can be in the top k is there. "
          "The dev numbers belong to the configuration that was chosen on dev: use the test row. All numbers count a passage as relevant only if it contains the golden span; a passage that also answers "
          "but holds no golden span (R-0016) counts as not relevant. The graded precision from your labels (`LABELLING.md`) measures that."]
    p = SWEEPS / name
    p.write_text("\n".join(L) + "\n", encoding="utf-8")
    (SWEEPS / name.replace(".md", ".json")).write_text(json.dumps(res, indent=1))
    return p


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--config", choices=list(LABELS), default="final"); a = ap.parse_args()
    r = run(a.config)
    print(write(r, "PRECISION.md" if a.config == "final" else f"PRECISION_{a.config}.md"))
    print({s: {k: round(r[s][k]["mean"], 3) for k in ("p@1", "p@3", "p@5", "np@3", "r_precision")} | {"n": r[s]["n"], "M": r[s]["relevant_chunks_M"]} for s in ("dev", "test")})
