"""Write the O30 review table for the author (rag-golden-review step 5): reports/layer1/REVIEW_v0.md. Values are read from files.

    PYTHONPATH=src:. .venv/bin/python -m gridsense.eval.review_table --snapshot <smoke snapshot json>
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from gridsense.config import ROOT, TRACK, load_config
from gridsense.ingest.corpus import load_corpus
from gridsense.ingest.parsers import split_frontmatter


def _cut(s: str, n: int = 70) -> str:
    s = " ".join(s.split()).replace("|", "/")
    return s if len(s) <= n else s[: n - 1] + "…"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--snapshot", type=Path, required=True)
    a = ap.parse_args()
    snap = json.loads(a.snapshot.read_text())
    items = {r["query_id"]: r for r in map(json.loads, (ROOT / snap["items_path"]).read_text().splitlines())}
    rows = [json.loads(l) for l in (ROOT / load_config()["golden_sets"]["retrieval"]["path"]).read_text().splitlines()]
    L = ["# O30 review table — golden retrieval set v0, notes, SOP, feeder docs", "",
         "Written for: the author. Generated by `gridsense.eval.review_table` from the files. Mark each row **accept**, **edit** "
         "(with the change) or **reject**. Only rows you accept in writing become `status: reviewed` (rag-golden-review step 6).",
         f"Rank = rank of the first relevant passage in the PRELIMINARY smoke run (`{a.snapshot.name}`); it is information for you, not a result.", "",
         "## 1. Retrieval queries (54; source: session B drafts, spans re-checked by session A)", "",
         "| id | type | split | query | golden span (short) → document | rank | doubt |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        it, doubt = items.get(r["query_id"], {}), []
        ctx = r["golden_contexts"]
        if any(c["recheck"]["result"] != "found_once" for c in ctx):
            doubt.append("span re-anchored: " + "; ".join(c["recheck"]["note"][:60] for c in ctx if c["recheck"]["note"]))
        rank = "-" if not r["answerable"] else (str(int(round(1 / it["mrr@10"]))) if it.get("mrr@10") else ">10")
        if not r["answerable"]:
            doubt.append("check that no corpus text answers it")
        elif rank == ">10":
            doubt.append("baseline misses top 10")
        span = " + ".join(f"{_cut(c['span'], 45)} → `{c['document_id']}`" for c in ctx) or "(none)"
        L.append(f"| {r['query_id']} | {r['query_type']} | {r['split']} | {_cut(r['query'], 60)} | {span} | {rank} | {'; '.join(doubt)} |")
    L += ["", "## 2. Notes and SOP (31 files; `status: draft`)", "", "| document | merged from | source_ref (short) | doubt |", "|---|---|---|---|"]
    for p in sorted((TRACK / "corpus" / "notes_v1").glob("*.md")) + sorted((TRACK / "corpus" / "sop_v1").glob("*.md")):
        m, _ = split_frontmatter(p.read_text(encoding="utf-8"))
        doubt = []
        if any(w in m.get("source_ref", "") for w in ("Anderson", "Kersting", "Phadke", "Guo", "Geifman", "Vovk", "Zadrozny", "Angelopoulos")):
            doubt.append("external textbook/paper: paraphrase unverified")
        if any(x.startswith("A:") for x in m.get("merged_from", [])):
            doubt.append("A's added sentences: numbers checked by A against the named reports")
        L.append(f"| `{m['document_id']}` | {', '.join(m.get('merged_from', []))} | {_cut(m.get('source_ref', ''), 60)} | {'; '.join(doubt)} |")
    L += ["", "## 3. Generated feeder documents (`corpus/feeder_v1/`, generator `feeder_docs_v2`)", "",
          "| document | content | doubt |", "|---|---|---|"]
    notes = {"feeder_fault_buses": "nearest-μPMU distances use the operated feeder (Sw7, Sw8 open); see reports/findings/paper1_open_switch.md"}
    for d in load_corpus(("feeder_v1",)):
        L.append(f"| `{d.document_id}` | {', '.join(' > '.join(s.path[1:]) or s.path[0] for s in d.sections if s.path)} | {notes.get(d.document_id, '')} |")
    out = TRACK / "reports" / "layer1" / "REVIEW_v0.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(out, len(L), "lines")


if __name__ == "__main__":
    main()
